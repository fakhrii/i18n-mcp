import * as path from "node:path";
import {
  dirExists,
  listFiles,
  toPosixPath,
  writeTextFile,
} from "../../utils/file-system.js";
import { analyzeProject } from "../discovery/project-analyzer.js";

export interface TypeGenOptions {
  projectPath?: string;
  outputPath?: string; // relative to projectRoot
  writeToDisk?: boolean;
}

export interface TypeGenResult {
  outputPath: string;
  content: string;
  namespaces: string[];
}

/**
 * Generates an i18next resources.d.ts type definition file from the source locale catalog.
 */
export async function generateI18nTypes(
  projectRoot: string,
  options: TypeGenOptions = {}
): Promise<TypeGenResult> {
  const analysis = await analyzeProject(projectRoot);
  const localeDir = analysis.i18n.localeDirectory;
  const sourceLocale = analysis.i18n.sourceLocale || "en";

  if (!localeDir) {
    throw new Error("Cannot generate types: project has no detected locale directory.");
  }

  const fullLocaleDir = path.join(projectRoot, localeDir);

  // Check if directory structure has subdirectories (e.g. locales/en/*.json)
  const fullSourceLocaleDir = path.join(fullLocaleDir, sourceLocale);
  const isSubdirStructure = await dirExists(fullSourceLocaleDir);

  // Determine output path: default to src/@types/resources.d.ts or @types/resources.d.ts
  let defaultOutput = "src/@types/resources.d.ts";
  const hasSrc = await dirExists(path.join(projectRoot, "src"));
  if (!hasSrc) {
    defaultOutput = "@types/resources.d.ts";
  }

  const relOutputPath = options.outputPath || defaultOutput;
  const absOutputDir = path.join(projectRoot, path.dirname(relOutputPath));

  const namespaces: string[] = [];
  const imports: string[] = [];
  const resourceProps: string[] = [];

  if (isSubdirStructure) {
    const files = await listFiles(fullSourceLocaleDir);
    for (const f of files.sort()) {
      if (f.endsWith(".json")) {
        const ns = path.basename(f, ".json");
        namespaces.push(ns);

        const absTargetJson = path.join(fullSourceLocaleDir, f);
        let relImport = toPosixPath(path.relative(absOutputDir, absTargetJson));
        if (!relImport.startsWith(".")) {
          relImport = `./${relImport}`;
        }

        // Clean identifier name
        const id = ns.replace(/[^a-zA-Z0-9_$]/g, "_");
        imports.push(`import type ${id} from "${relImport}";`);
        resourceProps.push(`    "${ns}": typeof ${id};`);
      }
    }
  } else {
    // Single file per locale: locales/en.json
    const sourceJsonFile = path.join(fullLocaleDir, `${sourceLocale}.json`);
    let relImport = toPosixPath(path.relative(absOutputDir, sourceJsonFile));
    if (!relImport.startsWith(".")) {
      relImport = `./${relImport}`;
    }

    const id = sourceLocale.replace(/[^a-zA-Z0-9_$]/g, "_");
    imports.push(`import type ${id} from "${relImport}";`);
    namespaces.push("translation");
    resourceProps.push(`    translation: typeof ${id};`);
  }

  const defaultNS = namespaces.includes("common") ? "common" : namespaces[0] || "translation";

  const content = [
    `// Auto-generated by i18n-mcp. Do not edit directly.`,
    ...imports,
    ``,
    `export interface Resources {`,
    ...resourceProps,
    `}`,
    ``,
    `declare module "i18next" {`,
    `  interface CustomTypeOptions {`,
    `    defaultNS: "${defaultNS}";`,
    `    resources: Resources;`,
    `  }`,
    `}`,
    ``,
  ].join("\n");

  if (options.writeToDisk ?? true) {
    const absOutputFile = path.join(projectRoot, relOutputPath);
    await writeTextFile(absOutputFile, content);
  }

  return {
    outputPath: toPosixPath(relOutputPath),
    content,
    namespaces,
  };
}
